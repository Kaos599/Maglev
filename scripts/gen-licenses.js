#!/usr/bin/env node
/**
 * Writes the two bundled data files the About pages read, so nothing is hand-written or fetched:
 *   constants/licenses.generated.ts      runtime dependencies (package.json) + pixelarticons + librqbit, with licences
 *   constants/releaseNotes.generated.ts  release-notes/<version>.md for every version
 * Licences come from node_modules/<pkg>/package.json; librqbit's from native/maglev-core/vendor/librqbit/Cargo.toml.
 * Other Rust crates are left out: their licences cannot be read offline, and we do not guess.
 * Run: node scripts/gen-licenses.js   (node_modules must be installed)
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

function repoUrl(p) {
  let u = typeof p.repository === 'string' ? p.repository : p.repository && p.repository.url;
  if (!u) return p.homepage || '';
  u = u.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://').replace(/^ssh:\/\/git@/, 'https://');
  if (/^github:/.test(u)) u = 'https://github.com/' + u.slice(7);
  if (!/^https:\/\//.test(u)) return p.homepage || '';
  const dir = p.repository && p.repository.directory;
  return dir && /github\.com/.test(u) ? `${u}/tree/HEAD/${dir}` : u;
}

const rows = [];
const names = [...Object.keys(pkg.dependencies), 'pixelarticons'].filter((n) => n !== 'maglev-engine');
for (const name of names) {
  const f = path.join(root, 'node_modules', name, 'package.json');
  if (!fs.existsSync(f)) throw new Error(`${name} is not installed; install dependencies first`);
  const p = JSON.parse(fs.readFileSync(f, 'utf8'));
  const license = typeof p.license === 'string' ? p.license : p.license && p.license.type;
  if (!license) throw new Error(`${name} has no license field`);
  rows.push({ name, version: p.version, license, url: repoUrl(p) });
}

const toml = fs.readFileSync(path.join(root, 'native/maglev-core/vendor/librqbit/Cargo.toml'), 'utf8');
const field = (k) => (toml.match(new RegExp(`^${k}\\s*=\\s*"([^"]+)"`, 'm')) || [])[1];
if (!field('license')) throw new Error('librqbit license not found in vendored Cargo.toml');
rows.push({ name: field('name'), version: field('version'), license: field('license'), url: field('repository') || '' });

rows.sort((a, b) => a.name.localeCompare(b.name));
const q = (s) => JSON.stringify(s);
const lic =
  `// generated by node scripts/gen-licenses.js; do not edit\n` +
  `export interface LicenseRow {\n  name: string;\n  version: string;\n  license: string;\n  url: string;\n}\n\n` +
  `export const LICENSES: readonly LicenseRow[] = [\n` +
  rows.map((r) => `  { name: ${q(r.name)}, version: ${q(r.version)}, license: ${q(r.license)}, url: ${q(r.url)} },`).join('\n') +
  `\n];\n`;
fs.writeFileSync(path.join(root, 'constants/licenses.generated.ts'), lic);

const dir = path.join(root, 'release-notes');
const notes = fs.readdirSync(dir).filter((f) => /^\d+\.\d+\.md$/.test(f)).sort();
const rn =
  `// generated by node scripts/gen-licenses.js from release-notes/*.md; do not edit\n` +
  `export const RELEASE_NOTES: Readonly<Record<string, string>> = {\n` +
  notes.map((f) => `  ${q(f.replace(/\.md$/, ''))}: ${q(fs.readFileSync(path.join(dir, f), 'utf8').trim())},`).join('\n') +
  `\n};\n`;
fs.writeFileSync(path.join(root, 'constants/releaseNotes.generated.ts'), rn);
console.log(`licenses: ${rows.length} rows, release notes: ${notes.length} versions`);
