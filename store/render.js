#!/usr/bin/env node
/**
 * Renders the store listing images.
 *
 *   node store/render.js                 everything
 *   node store/render.js --only search   one screen and its frame
 *   node store/render.js --out <dir>     write somewhere other than store/out
 *   node store/render.js --fonts inter   load store/fonts/inter.css over every page (font trials);
 *                                        writes to store/out/fonts/inter unless --out is given
 *   node store/render.js --config screens.v2.json
 *                                        another set: its "out" folder, screen files and templates
 *   node store/render.js --config screens.v2.json --screen-fonts inter
 *                                        load store/fonts/inter.css on the phone screens only
 *                                        (captions keep their own font); writes to <out>-inter
 *
 * A config may set "out" (folder under store/), "screenFonts" (a store/fonts/<name>.css for the
 * screens only), and per screen "screen" (the HTML file, default <id>.html) and "template".
 * "feature.template" picks the feature graphic page (default feature.html).
 *
 * Steps
 *   1. Writes store/screens/icons.js from components/icons.generated.ts, so the mock screens use
 *      the app's own Pixelarticons paths.
 *   2. Renders each mock screen (store/screens/<id>.html) at 360x800 with a device scale factor
 *      of 3, giving a 1080x2400 PNG in <out>/screens/.
 *   3. Places each screen PNG in its frame template (store/frames/<template>.html) and writes
 *      <out>/<id>.png at the template's size (1080x1920).
 *   4. Renders the feature graphic (1024x500) and a contact sheet of every frame.
 *
 * Browser: Playwright's Chromium. No dependency is added to package.json. The script looks for
 * playwright-core in node_modules, then in the npx cache, and if neither has it, runs
 * `npx --yes playwright-core@1.58.2 --version` once to fetch it. 1.58.2 matches the cached
 * chromium-1208 build in ~/Library/Caches/ms-playwright.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execSync } = require('child_process');
const { pathToFileURL } = require('url');

const PW_VERSION = '1.58.2';
const ROOT = path.resolve(__dirname, '..');
const STORE = __dirname;

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : undefined;
}
const ONLY = arg('--only');
const FONTS = arg('--fonts');
const FONT_CSS = FONTS ? path.join(STORE, 'fonts', `${FONTS}.css`) : null;
if (FONT_CSS && !fs.existsSync(FONT_CSS)) throw new Error(`no font variant: ${path.relative(ROOT, FONT_CSS)}`);
const CONFIG = path.resolve(STORE, arg('--config') || 'screens.json');
const CFG = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
const SCREEN_FONTS = arg('--screen-fonts') || CFG.screenFonts || null;
const SCREEN_FONT_CSS = SCREEN_FONTS ? path.join(STORE, 'fonts', `${SCREEN_FONTS}.css`) : null;
if (SCREEN_FONT_CSS && !fs.existsSync(SCREEN_FONT_CSS)) throw new Error(`no font variant: ${path.relative(ROOT, SCREEN_FONT_CSS)}`);
const BASE_OUT = CFG.out ? path.join(STORE, CFG.out) : path.join(STORE, 'out');
const OUT = path.resolve(
  arg('--out') ||
    (FONTS ? path.join(BASE_OUT, 'fonts', FONTS) : arg('--screen-fonts') ? `${BASE_OUT}-${SCREEN_FONTS}` : BASE_OUT),
);

// ---------------------------------------------------------------- Playwright

function findInNpxCache() {
  const base = path.join(os.homedir(), '.npm', '_npx');
  if (!fs.existsSync(base)) return null;
  for (const d of fs.readdirSync(base)) {
    const dir = path.join(base, d, 'node_modules', 'playwright-core');
    try {
      if (require(path.join(dir, 'package.json')).version === PW_VERSION) return dir;
    } catch {
      /* not this one */
    }
  }
  return null;
}

function loadPlaywright() {
  if (process.env.PLAYWRIGHT_CORE) return require(process.env.PLAYWRIGHT_CORE);
  for (const name of ['playwright-core', 'playwright']) {
    try {
      return require(require.resolve(name, { paths: [ROOT] }));
    } catch {
      /* try the next */
    }
  }
  let dir = findInNpxCache();
  if (!dir) {
    console.log(`Fetching playwright-core@${PW_VERSION} into the npx cache (not package.json)…`);
    execSync(`npx --yes playwright-core@${PW_VERSION} --version`, { stdio: 'inherit' });
    dir = findInNpxCache();
  }
  if (!dir) throw new Error(`playwright-core@${PW_VERSION} not found. Set PLAYWRIGHT_CORE to its folder.`);
  return require(dir);
}

// ---------------------------------------------------------------- icons

function writeIcons() {
  const src = fs.readFileSync(path.join(ROOT, 'components', 'icons.generated.ts'), 'utf8');
  const m = src.match(/ICON_PATHS = (\{[\s\S]*?\n\})/);
  if (!m) throw new Error('ICON_PATHS not found in components/icons.generated.ts');
  const paths = JSON.parse(m[1].replace(/,\s*\}$/, '}'));
  const body =
    '// Generated by store/render.js from components/icons.generated.ts (Pixelarticons, MIT). Do not edit.\n' +
    `window.ICON_PATHS = ${JSON.stringify(paths)};\n`;
  fs.writeFileSync(path.join(STORE, 'screens', 'icons.js'), body);
  return Object.keys(paths).length;
}

// ---------------------------------------------------------------- render

async function settle(page, screen = false) {
  // A font variant is a plain stylesheet added last, so it wins over the page's own rules.
  // --fonts applies to every page; screenFonts only to the phone screens.
  const css = [FONT_CSS, screen ? SCREEN_FONT_CSS : null].filter(Boolean);
  for (const f of css) await page.addStyleTag({ content: fs.readFileSync(f, 'utf8') });
  if (css.length) await page.waitForTimeout(150); // let the new faces start loading before fonts.ready is read
  await page.evaluate(async () => {
    await document.fonts.ready;
    await Promise.all([...document.images].map((img) => (img.complete ? null : img.decode().catch(() => null))));
  });
  const errors = await page.evaluate(() => [...document.querySelectorAll('i.px')].filter((i) => !i.querySelector('svg')).map((i) => i.dataset.i));
  if (errors.length) throw new Error(`missing icons: ${errors.join(', ')}`);
}

async function checkFonts(page, label) {
  // A face that failed to load means a wrong path under node_modules/@expo-google-fonts.
  const bad = await page.evaluate(() => [...document.fonts].filter((f) => f.status === 'error').map((f) => `${f.family} ${f.weight}`));
  if (bad.length) throw new Error(`${label}: fonts failed to load: ${bad.join(', ')}`);
}

async function main() {
  const cfg = CFG;
  const n = writeIcons();
  console.log(`icons.js: ${n} Pixelarticons paths`);
  console.log(`config ${path.relative(ROOT, CONFIG)} -> ${path.relative(ROOT, OUT)}${SCREEN_FONTS ? ` (screens in ${SCREEN_FONTS})` : ''}`);

  fs.mkdirSync(path.join(OUT, 'screens'), { recursive: true });
  const { chromium } = loadPlaywright();
  const browser = await chromium.launch();
  const errors = [];

  try {
    // Screens: 360x800 dp at 3x = 1080x2400.
    const phone = await browser.newPage({ viewport: { width: 360, height: 800 }, deviceScaleFactor: 3 });
    phone.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
    phone.on('pageerror', (e) => errors.push(String(e)));
    for (const s of cfg.screens) {
      if (ONLY && s.id !== ONLY) continue;
      const file = path.join(STORE, 'screens', s.screen || `${s.id}.html`);
      if (!fs.existsSync(file)) {
        console.warn(`skip ${s.id}: ${path.relative(ROOT, file)} not found`);
        continue;
      }
      await phone.goto(pathToFileURL(file).href);
      await settle(phone, true);
      await checkFonts(phone, s.id);
      const out = path.join(OUT, 'screens', `${s.id}.png`);
      await phone.screenshot({ path: out, clip: { x: 0, y: 0, width: 360, height: 800 } });
      console.log(`screen  ${path.relative(ROOT, out)}  1080x2400`);
    }
    await phone.close();

    // Frames around each screen.
    const framed = [];
    for (const s of cfg.screens) {
      if (ONLY && s.id !== ONLY) continue;
      const shot = path.join(OUT, 'screens', `${s.id}.png`);
      if (!fs.existsSync(shot)) {
        console.warn(`skip frame ${s.id}: no screen PNG`);
        continue;
      }
      const tpl = path.join(STORE, 'frames', `${s.template}.html`);
      const q = new URLSearchParams({
        shot: pathToFileURL(shot).href,
        h: s.headline,
        s: s.subline,
        color: s.color || 'white',
        seed: s.id,
        ...(s.focusY != null ? { focusY: String(s.focusY) } : {}),
        ...(s.focusX != null ? { focusX: String(s.focusX) } : {}),
      });
      const size = cfg.frameSize;
      const page = await browser.newPage({ viewport: { width: size.width, height: size.height }, deviceScaleFactor: 1 });
      page.on('pageerror', (e) => errors.push(String(e)));
      await page.goto(`${pathToFileURL(tpl).href}?${q}`);
      await settle(page);
      await checkFonts(page, `frame ${s.id}`);
      const out = path.join(OUT, `${s.id}.png`);
      await page.screenshot({ path: out, clip: { x: 0, y: 0, width: size.width, height: size.height } });
      await page.close();
      framed.push(out);
      console.log(`frame   ${path.relative(ROOT, out)}  ${size.width}x${size.height}  (${s.template})`);
    }

    // Feature graphic.
    if (!ONLY || ONLY === 'feature') {
      const f = cfg.feature;
      const page = await browser.newPage({ viewport: { width: 1024, height: 500 }, deviceScaleFactor: 1 });
      page.on('pageerror', (e) => errors.push(String(e)));
      const q = new URLSearchParams({ s: f.subline });
      await page.goto(`${pathToFileURL(path.join(STORE, 'frames', f.template || 'feature.html')).href}?${q}`);
      await settle(page);
      const out = path.join(OUT, 'feature.png');
      await page.screenshot({ path: out, clip: { x: 0, y: 0, width: 1024, height: 500 } });
      await page.close();
      console.log(`feature ${path.relative(ROOT, out)}  1024x500`);
    }

    // Contact sheet of every framed PNG, for review only.
    if (!ONLY && framed.length) {
      const sheet = path.join(OUT, '.contact-sheet.html');
      const cells = framed.map((p) => `<img src="${pathToFileURL(p).href}">`).join('');
      const feature = fs.existsSync(path.join(OUT, 'feature.png')) ? `<img class="f" src="${pathToFileURL(path.join(OUT, 'feature.png')).href}">` : '';
      fs.writeFileSync(
        sheet,
        `<!doctype html><style>body{margin:0;background:#05070A;padding:40px;display:flex;flex-wrap:wrap;gap:24px;width:${4 * 270 + 3 * 24 + 80}px}img{width:270px;height:480px;outline:1px solid #1F2937}img.f{width:512px;height:250px}</style>${cells}${feature}`,
      );
      const page = await browser.newPage({ viewport: { width: 4 * 270 + 3 * 24 + 80, height: 400 }, deviceScaleFactor: 1 });
      await page.goto(pathToFileURL(sheet).href);
      await settle(page);
      const out = path.join(OUT, 'contact-sheet.png');
      await page.screenshot({ path: out, fullPage: true });
      await page.close();
      fs.unlinkSync(sheet);
      console.log(`sheet   ${path.relative(ROOT, out)}`);
    }
  } finally {
    await browser.close();
  }
  if (errors.length) {
    console.error('Page errors:\n  ' + errors.join('\n  '));
    process.exit(1);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
