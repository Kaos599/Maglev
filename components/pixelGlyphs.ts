export type PixelIconName = keyof typeof GLYPHS;

export const GLYPH_GRID = 12;

/** Returns a list of problems (empty when every glyph is 12x12 of '.'/'#'). */
export function validateGlyphs(): string[] {
  const errs: string[] = [];
  (Object.keys(GLYPHS) as PixelIconName[]).forEach((name) => {
    const rows: readonly string[] = GLYPHS[name];
    if (rows.length !== GLYPH_GRID) errs.push(`${name}: ${rows.length} rows`);
    rows.forEach((r, i) => {
      if (r.length !== GLYPH_GRID || /[^.#]/.test(r)) errs.push(`${name} row ${i}: "${r}"`);
    });
  });
  return errs;
}
