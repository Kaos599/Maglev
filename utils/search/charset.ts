// Windows-1251 decoding for sources that serve Cyrillic pages without UTF-8 (MegaPeer).
// Hermes' TextDecoder only covers UTF-8, so the table is spelled out here.

const HIGH = [
  0x0402, 0x0403, 0x201a, 0x0453, 0x201e, 0x2026, 0x2020, 0x2021, 0x20ac, 0x2030, 0x0409, 0x2039, 0x040a, 0x040c, 0x040b, 0x040f,
  0x0452, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, 0x0098, 0x2122, 0x0459, 0x203a, 0x045a, 0x045c, 0x045b, 0x045f,
  0x00a0, 0x040e, 0x045e, 0x0408, 0x00a4, 0x0490, 0x00a6, 0x00a7, 0x0401, 0x00a9, 0x0404, 0x00ab, 0x00ac, 0x00ad, 0x00ae, 0x0407,
  0x00b0, 0x00b1, 0x0406, 0x0456, 0x0491, 0x00b5, 0x00b6, 0x00b7, 0x0451, 0x2116, 0x0454, 0x00bb, 0x0458, 0x0405, 0x0455, 0x0457,
];

export function decodeWindows1251(bytes: Uint8Array): string {
  const parts: string[] = [];
  const CHUNK = 8192;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    const codes: number[] = [];
    const end = Math.min(bytes.length, i + CHUNK);
    for (let j = i; j < end; j++) {
      const b = bytes[j];
      codes.push(b < 0x80 ? b : b < 0xc0 ? HIGH[b - 0x80] : 0x0410 + (b - 0xc0));
    }
    parts.push(String.fromCharCode(...codes));
  }
  return parts.join('');
}

export function isWindows1251(contentType: string): boolean {
  return /charset\s*=\s*"?(windows-1251|cp1251)/i.test(contentType);
}
